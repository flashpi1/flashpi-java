/*
 * Keeps the SDK's copy of the Flashpi API contract and the models generated from it in sync.
 *
 *   java scripts/OpenApi.java sync      download the public OpenAPI document, then generate
 *   java scripts/OpenApi.java generate  regenerate the models from openapi/openapi.json
 *   java scripts/OpenApi.java check     fail when the generated models are out of date (CI)
 *
 * It runs on the JDK alone (Java 11 or later, as a single-file program): no dependency, no build.
 *
 * The source is the public document the docs publish (https://flashpi.com.ec/docs/openapi.json),
 * because the API repository is private. Override it with FLASHPI_OPENAPI_URL, or point
 * FLASHPI_OPENAPI_FILE at a local file (for example a flashpi-api checkout).
 *
 * Every component schema becomes a class with typed getters and a builder, a Java enum or, for a
 * discriminated oneOf, an interface; every list operation's query becomes a class too. Inline enums
 * with the same values share one Java enum. Each generated file starts with GENERATED_MARKER; the
 * generator deletes generated files that are no longer produced and never touches the hand-written
 * ones next to them. It fails on any construct it does not know, so a change in the document can
 * never be translated silently into a wrong type.
 */

