  public static void main(String[] args) throws Exception {
    String mode = args.length > 0 ? args[0] : "generate";
    if (args.length > 1 || !List.of("sync", "generate", "check").contains(mode)) {
      System.err.println("Usage: java scripts/OpenApi.java sync|generate|check");
      System.exit(2);
    }
    if (mode.equals("sync")) {
      String[] downloaded = download();
      Object parsed = Json.parse(downloaded[1]);
      if (!(parsed instanceof Map)
          || !((Map<?, ?>) parsed).containsKey("openapi")
          || !((Map<?, ?>) parsed).containsKey("paths")) {
        fail("The downloaded file is not an OpenAPI document");
      }
      String text = downloaded[1].endsWith("\n") ? downloaded[1] : downloaded[1] + "\n";
      Files.writeString(CONTRACT, text, StandardCharsets.UTF_8);
      System.out.println("Copied " + downloaded[0] + " to openapi/openapi.json");
    }
    Map<String, String> files = generate(Files.readString(CONTRACT, StandardCharsets.UTF_8));
    Map<String, String> current = currentGeneratedFiles();
    if (mode.equals("check")) {
      List<String> stale = new ArrayList<>();
      for (Map.Entry<String, String> file : files.entrySet()) {
        if (!file.getValue().equals(current.get(file.getKey()))) {
          stale.add(file.getKey());
        }
      }
      for (String name : current.keySet()) {
        if (!files.containsKey(name)) {
          stale.add(name + " (no longer generated)");
        }
      }
      if (!stale.isEmpty()) {
        System.err.println(
            "The models are out of date: run `java scripts/OpenApi.java generate`. Stale: "
                + String.join(", ", stale));
        System.exit(1);
      }
      System.out.println(files.size() + " generated models match openapi/openapi.json");
      return;
    }
    Files.createDirectories(MODELS);
    for (String name : current.keySet()) {
      if (!files.containsKey(name)) {
        Files.delete(MODELS.resolve(name));
      }
    }
    for (Map.Entry<String, String> file : files.entrySet()) {
      Path path = MODELS.resolve(file.getKey());
      if ((Files.exists(path) && !current.containsKey(file.getKey()))
          || Files.exists(HAND_WRITTEN.resolve(file.getKey()))) {
        fail(file.getKey() + " is hand-written: the generator will not overwrite it");
      }
      Files.writeString(path, file.getValue(), StandardCharsets.UTF_8);
    }
    System.out.println("Wrote " + files.size() + " models to " + ROOT.relativize(MODELS));
  }

  /** The generated files now in the models directory, by file name. */
  static Map<String, String> currentGeneratedFiles() throws IOException {
    Map<String, String> files = new TreeMap<>();
    if (!Files.isDirectory(MODELS)) {
      return files;
    }
    try (Stream<Path> paths = Files.list(MODELS)) {
      for (Path path : paths.collect(Collectors.toList())) {
        String text = Files.readString(path, StandardCharsets.UTF_8);
        if (text.startsWith(GENERATED_MARKER)) {
          files.put(path.getFileName().toString(), text);
        }
      }
    }
    return files;
  }

  static Map<String, String> generate(String contract) {
    Object document = Json.parse(contract);
    // First pass: find every inline enum, so the ones with the same values share one name.
    Generator collecting = new Generator(document, null);
    collecting.run();
    Map<String, String> enumNames = collecting.enumNames();
    Generator generator = new Generator(document, enumNames);
    generator.run();
    return generator.files();
  }

  // The generator.

  static final class Generator {
    final Map<String, Object> document;
    final Map<String, Object> schemas;
    final Map<String, Object> parameters;

    /** Null while collecting the inline enums. */
    final Map<String, String> enumNames;

    final Map<String, Definition> definitions = new TreeMap<>();

    /** Inline enums in the order they appear: their place and values. */
    final List<String[]> enumPlaces = new ArrayList<>();

    final Map<String, List<String>> enumValues = new LinkedHashMap<>();

    Generator(Object document, Map<String, String> enumNames) {
      this.document = asMap(document, "document");
      Object version = this.document.get("openapi");
      if (!(version instanceof String) || !((String) version).startsWith("3.1")) {
        fail("Only OpenAPI 3.1 documents are supported");
      }
      Map<String, Object> components =
          asMap(this.document.getOrDefault("components", Map.of()), "components");
      this.schemas = asMap(components.getOrDefault("schemas", Map.of()), "components.schemas");
      this.parameters =
          asMap(components.getOrDefault("parameters", Map.of()), "components.parameters");
      this.enumNames = enumNames;
    }

    void run() {
      for (String name : new TreeSet<>(schemas.keySet())) {
        defineComponent(name, asMap(schemas.get(name), name));
      }
      defineQueries();
      if (enumNames != null) {
        defineWebhookEvent();
        linkUnions();
      }
    }

    void define(Definition definition) {
      if (definitions.containsKey(definition.name)) {
        fail("Two definitions are named " + definition.name);
      }
      if (!IDENTIFIER.matcher(definition.name).matches()
          || JAVA_KEYWORDS.contains(definition.name)) {
        fail(definition.name + " is not a valid Java class name");
      }
      definitions.put(definition.name, definition);
    }

    // Inline enums: names shared by value.

    /** The names of the inline enums, by place, once every place is known. */
    Map<String, String> enumNames() {
      Map<String, List<String[]>> groups = new LinkedHashMap<>();
      for (String[] place : enumPlaces) {
        groups.computeIfAbsent(place[2], key -> new ArrayList<>()).add(place);
      }
      Map<String, String> names = new LinkedHashMap<>();
      Set<String> firstPlaces = new LinkedHashSet<>();
      Set<String> used = new LinkedHashSet<>(schemas.keySet());
      for (List<String[]> group : groups.values()) {
        String[] first = group.get(0);
        firstPlaces.add(first[0]);
        String name = SHARED_ENUM_NAMES.getOrDefault(first[0], first[1]);
        if (!used.add(name)) {
          fail("Two enums would be named " + name + " (first at " + first[0] + ")");
        }
        for (String[] place : group) {
          names.put(place[0], name);
        }
      }
      for (String place : SHARED_ENUM_NAMES.keySet()) {
        if (!firstPlaces.contains(place)) {
          fail("SHARED_ENUM_NAMES names " + place + ", which is not where an enum first appears");
        }
      }
      return names;
    }

    // Translation of schemas into Java types.

    void checkKeywords(Map<String, Object> schema, String where) {
      Set<String> unknown = new TreeSet<>(schema.keySet());
      unknown.removeAll(ANNOTATION_KEYWORDS);
      unknown.removeAll(STRUCTURE_KEYWORDS);
      if (!unknown.isEmpty()) {
        fail(where + ": unsupported keywords " + unknown);
      }
    }

    String reference(Map<String, Object> schema, String where) {
      String target = asString(schema.get("$ref"), where);
      String prefix = "#/components/schemas/";
      String name = target.startsWith(prefix) ? target.substring(prefix.length()) : "";
      if (!schemas.containsKey(name)) {
        fail(where + ": unknown reference " + target);
      }
      Set<String> rest = new TreeSet<>(schema.keySet());
      rest.removeAll(ANNOTATION_KEYWORDS);
      if (rest.size() > 1) {
        fail(where + ": $ref with sibling keywords");
      }
      return name;
    }

    List<String> typesOf(Map<String, Object> schema, String where) {
      Object declared = schema.get("type");
      if (declared == null) {
        return new ArrayList<>();
      }
      if (declared instanceof String) {
        return new ArrayList<>(List.of((String) declared));
      }
      List<String> types = new ArrayList<>();
      for (Object item : asList(declared, where)) {
        types.add(asString(item, where));
      }
      return types;
    }

    /**
     * The Java type of a schema. Inline enums and objects become definitions named `hint`; `place`
     * names the spot in the document for inline enums.
     */
    JType render(Map<String, Object> schema, String hint, String place, String where) {
      checkKeywords(schema, where);
      if (schema.containsKey("$ref")) {
        return referenced(reference(schema, where));
      }
      for (String combinator : List.of("allOf", "anyOf", "oneOf")) {
        if (schema.containsKey(combinator)) {
          return renderCombination(schema, combinator, hint, place, where);
        }
      }
      List<String> types = typesOf(schema, where);
      types.remove("null");
      if (schema.containsKey("not") && !types.equals(List.of("object"))) {
        fail(where + ": `not` is only supported on objects");
      }
      if (schema.containsKey("const")) {
        Object value = schema.get("const");
        if (!(value instanceof String)) {
          fail(where + ": only string constants are supported");
        }
        return JType.simple("String", "Types.STRING");
      }
      if (schema.containsKey("enum")) {
        return renderEnum(schema, hint, place, where);
      }
      if (types.size() > 1) {
        fail(where + ": several non-null types");
      }
      if (types.isEmpty() && !schema.containsKey("properties")) {
        Set<String> rest = new TreeSet<>(schema.keySet());
        rest.removeAll(ANNOTATION_KEYWORDS);
        if (rest.isEmpty() || rest.equals(Set.of("type"))) {
          return JType.simple("Object", "Types.ANY");
        }
        fail(where + ": a schema without a type");
      }
      String kind = types.isEmpty() ? "object" : types.get(0);
      switch (kind) {
        case "string":
          Object format = schema.get("format");
          if ("date".equals(format)) {
            return JType.simple("LocalDate", "Types.DATE").importing("java.time.LocalDate");
          }
          if ("date-time".equals(format)) {
            return JType.simple("OffsetDateTime", "Types.DATE_TIME")
                .importing("java.time.OffsetDateTime");
          }
          if ("binary".equals(format)) {
            fail(where + ": binary strings are only supported in multipart bodies");
          }
          return JType.simple("String", "Types.STRING");
        case "integer":
          Object maximum = schema.get("maximum");
          Object minimum = schema.get("minimum");
          boolean fitsInt =
              maximum instanceof BigDecimal
                  && ((BigDecimal) maximum).compareTo(BigDecimal.valueOf(Integer.MAX_VALUE)) <= 0
                  && (!(minimum instanceof BigDecimal)
                      || ((BigDecimal) minimum).compareTo(BigDecimal.valueOf(Integer.MIN_VALUE))
                          >= 0);
          // Without bounds the API sends small numbers (counts, HTTP statuses): Integer, which a
          // builder takes from an int literal. Long only when the bounds need it.
          if (maximum == null || fitsInt) {
            return JType.simple("Integer", "Types.INTEGER");
          }
          return JType.simple("Long", "Types.LONG");
        case "number":
          return JType.simple("Double", "Types.NUMBER");
        case "boolean":
          return JType.simple("Boolean", "Types.BOOLEAN");
        case "array":
          {
            Map<String, Object> items =
                asMap(schema.getOrDefault("items", Map.of()), where + ".items");
            JType item = render(items, hint + "Item", place + "[]", where + ".items");
            return JType.list(item);
          }
        case "object":
          return renderObject(schema, hint, place, where);
        default:
          fail(where + ": unsupported type " + kind);
          return null;
      }
    }

    JType referenced(String name) {
      Map<String, Object> schema = asMap(schemas.get(name), name);
      if (schema.containsKey("enum")) {
        return JType.enumeration(name);
      }
      if (schema.containsKey("oneOf")) {
        return JType.union(name);
      }
      return JType.model(name);
    }

    JType renderEnum(Map<String, Object> schema, String hint, String place, String where) {
      List<String> values = new ArrayList<>();
      for (Object value : asList(schema.get("enum"), where + ".enum")) {
        if (value == null) {
          continue;
        }
        if (!(value instanceof String)) {
          fail(where + ": only string enums are supported");
        }
        values.add((String) value);
      }
      if (values.isEmpty()) {
        fail(where + ": an enum with no values");
      }
      String key = String.join("\u0000", new TreeSet<>(values));
      if (enumNames == null) {
        enumPlaces.add(new String[] {place, hint, key});
        return JType.enumeration(hint);
      }
      String name = enumNames.get(place);
      if (name == null) {
        fail(where + ": an enum the first pass did not see");
      }
      if (!definitions.containsKey(name)) {
        define(enumDefinition(name, describe(schema), values, place));
      }
      return JType.enumeration(name);
    }

    JType renderCombination(
        Map<String, Object> schema, String combinator, String hint, String place, String where) {
      Set<String> structure = new TreeSet<>(schema.keySet());
      structure.retainAll(STRUCTURE_KEYWORDS);
      structure.removeAll(Set.of(combinator, "discriminator"));
      if (!structure.isEmpty()) {
        fail(where + ": " + combinator + " with " + structure);
      }
      List<Map<String, Object>> members = new ArrayList<>();
      for (Object member : asList(schema.get(combinator), where)) {
        members.add(asMap(member, where));
      }
      if (combinator.equals("allOf")) {
        if (members.size() != 1) {
          fail(where + ": allOf is only supported with one member");
        }
        return render(members.get(0), hint, place, where + ".allOf[0]");
      }
      if (combinator.equals("anyOf")) {
        // Only "this or null": Java references are nullable.
        List<Map<String, Object>> rest = new ArrayList<>();
        for (Map<String, Object> member : members) {
          if (!member.equals(Map.of("type", "null"))) {
            rest.add(member);
          }
        }
        if (rest.size() != 1) {
          fail(where + ": anyOf is only supported as one schema or null");
        }
        return render(rest.get(0), hint, place, where + ".anyOf");
      }
      fail(where + ": oneOf is only supported as a component schema with a discriminator");
      return null;
    }

    JType renderObject(Map<String, Object> schema, String hint, String place, String where) {
      Object properties = schema.get("properties");
      Object extra = schema.get("additionalProperties");
      if (properties == null) {
        if (extra instanceof Map) {
          JType value =
              render(
                  asMap(extra, where),
                  hint + "Value",
                  place + "{}",
                  where + ".additionalProperties");
          return JType.map(value);
        }
        return JType.map(JType.simple("Object", "Types.ANY"));
      }
      defineClass(hint, schema, place, where);
      return JType.model(hint);
    }

    // Definitions.

    void defineClass(String name, Map<String, Object> schema, String place, String where) {
      Set<String> unexpected = new TreeSet<>(schema.keySet());
      unexpected.retainAll(Set.of("allOf", "anyOf", "oneOf", "enum", "const", "items"));
      List<String> types = typesOf(schema, where);
      if (!unexpected.isEmpty() || !(types.isEmpty() || types.equals(List.of("object")))) {
        fail(where + ": properties mixed with other types");
      }
      if (schema.containsKey("not")) {
        checkNot(schema, where);
      }
      Object extra = schema.get("additionalProperties");
      if (extra != null && !(extra instanceof Boolean)) {
        fail(where + ": typed members with typed additionalProperties");
      }
      Map<String, Object> properties =
          asMap(schema.getOrDefault("properties", Map.of()), where + ".properties");
      Set<String> required = new LinkedHashSet<>();
      for (Object item : asList(schema.getOrDefault("required", List.of()), where)) {
        required.add(asString(item, where));
      }
      Set<String> missing = new TreeSet<>(required);
      missing.removeAll(properties.keySet());
      if (!missing.isEmpty()) {
        fail(where + ": required members without a schema: " + missing);
      }
      ClassDef definition = new ClassDef(name, describe(schema));
      if (enumNames != null) {
        define(definition);
      }
      for (Map.Entry<String, Object> entry : properties.entrySet()) {
        String key = entry.getKey();
        if (!IDENTIFIER.matcher(key).matches()
            || JAVA_KEYWORDS.contains(key)
            || RESERVED_MEMBERS.contains(key)) {
          fail(where + ": the member " + key + " cannot be a Java method name");
        }
        Map<String, Object> member = asMap(entry.getValue(), where + "." + key);
        JType type = render(member, name + upperFirst(key), place + "." + key, where + "." + key);
        boolean secret =
            type.javaType.equals("String")
                && (SECRET_MEMBER.matcher(key).matches()
                    || "password".equals(member.get("format")));
        definition.members.add(
            new MemberDef(key, type, describe(member), required.contains(key), secret));
      }
    }

    void checkNot(Map<String, Object> schema, String where) {
      Map<String, Object> forbidden = asMap(schema.get("not"), where + ".not");
      if (!forbidden.keySet().equals(Set.of("required"))) {
        fail(where + ": `not` is only supported as not.required");
      }
      Map<String, Object> properties = asMap(schema.getOrDefault("properties", Map.of()), where);
      for (Object key : asList(forbidden.get("required"), where + ".not.required")) {
        if (properties.containsKey(asString(key, where))) {
          fail(where + ": " + key + " is both declared and forbidden");
        }
      }
    }

    void defineComponent(String name, Map<String, Object> schema) {
      String where = "components.schemas." + name;
      checkKeywords(schema, where);
      if (schema.containsKey("oneOf")) {
        defineUnion(name, schema, where);
        return;
      }
      if (schema.containsKey("enum")) {
        List<String> types = typesOf(schema, where);
        if (!types.equals(List.of("string"))) {
          fail(where + ": a component enum must be a string");
        }
        List<String> values = new ArrayList<>();
        for (Object value : asList(schema.get("enum"), where)) {
          values.add(asString(value, where));
        }
        if (enumNames != null) {
          define(enumDefinition(name, describe(schema), values, name));
        }
        return;
      }
      if (schema.containsKey("properties") || typesOf(schema, where).equals(List.of("object"))) {
        if (!schema.containsKey("properties")
            && schema.get("additionalProperties") instanceof Map) {
          fail(where + ": a component map");
        }
        defineClass(name, schema, name, where);
        return;
      }
      fail(where + ": unsupported component schema");
    }

    void defineUnion(String name, Map<String, Object> schema, String where) {
      Set<String> structure = new TreeSet<>(schema.keySet());
      structure.retainAll(STRUCTURE_KEYWORDS);
      if (!structure.equals(Set.of("oneOf", "discriminator"))) {
        fail(where + ": oneOf is only supported with a discriminator and nothing else");
      }
      Map<String, Object> discriminator =
          asMap(schema.get("discriminator"), where + ".discriminator");
      String property =
          asString(discriminator.get("propertyName"), where + ".discriminator.propertyName");
      Map<String, Object> mapping =
          asMap(discriminator.getOrDefault("mapping", Map.of()), where + ".mapping");
      List<String> members = new ArrayList<>();
      for (Object member : asList(schema.get("oneOf"), where)) {
        Map<String, Object> memberSchema = asMap(member, where);
        if (!memberSchema.containsKey("$ref")) {
          fail(where + ": a discriminated union must list references only");
        }
        members.add(reference(memberSchema, where));
      }
      Map<String, String> values = new LinkedHashMap<>();
      for (Map.Entry<String, Object> entry : mapping.entrySet()) {
        String target = asString(entry.getValue(), where).replace("#/components/schemas/", "");
        if (!members.contains(target)) {
          fail(where + ": mapping " + entry.getKey() + " points outside the union");
        }
        if (!allowedValues(target, property).contains(entry.getKey())) {
          fail(where + ": " + target + "." + property + " does not allow " + entry.getKey());
        }
        values.put(entry.getKey(), target);
      }
      for (String member : members) {
        if (!values.containsValue(member)) {
          fail(where + ": " + member + " has no discriminator value");
        }
      }
      if (enumNames == null) {
        return;
      }
      UnionDef union = new UnionDef(name, describe(schema), property, members, values);
      if (name.equals(EVENT_UNION)) {
        union.fallback = EVENT_FALLBACK;
        union.parent = WEBHOOK_EVENT;
      }
      define(union);
    }

    /** The values a member's discriminant property allows (its enum or its const). */
    List<String> allowedValues(String member, String property) {
      Map<String, Object> schema = asMap(schemas.get(member), member);
      Map<String, Object> properties = asMap(schema.getOrDefault("properties", Map.of()), member);
      Map<String, Object> discriminant =
          asMap(properties.getOrDefault(property, Map.of()), member + "." + property);
      List<String> allowed = new ArrayList<>();
      if (discriminant.containsKey("const")) {
        allowed.add(asString(discriminant.get("const"), member));
      }
      for (Object value : asList(discriminant.getOrDefault("enum", List.of()), member)) {
        allowed.add(asString(value, member));
      }
      return allowed;
    }

    /** WebhookEvent: every Event, plus the endpoint verification handshake. */
    void defineWebhookEvent() {
      Definition event = definitions.get(EVENT_UNION);
      if (!(event instanceof UnionDef)
          || !(definitions.get(VERIFICATION_EVENT) instanceof ClassDef)) {
        fail(
            "The contract lost "
                + EVENT_UNION
                + " or "
                + VERIFICATION_EVENT
                + ": update WEBHOOK_EVENT");
      }
      if (!(definitions.get(EVENT_FALLBACK) instanceof ClassDef)) {
        fail("The contract lost " + EVENT_FALLBACK + ": update EVENT_FALLBACK");
      }
      UnionDef events = (UnionDef) event;
      List<String> members = new ArrayList<>(events.members);
      members.add(VERIFICATION_EVENT);
      Map<String, String> values = new LinkedHashMap<>(events.values);
      for (String value : allowedValues(VERIFICATION_EVENT, events.property)) {
        values.put(value, VERIFICATION_EVENT);
      }
      UnionDef union =
          new UnionDef(
              WEBHOOK_EVENT,
              "What a webhook carries: an event (see Event) or the activation handshake of an"
                  + " endpoint (WebhookEndpointVerificationEvent). Not in the API contract: the SDK"
                  + " adds it. An event of a type this version of the SDK does not know is read as an"
                  + " EventThin.",
              events.property,
              members,
              values);
      union.fallback = EVENT_FALLBACK;
      define(union);
    }

    /**
     * Each class implements the unions it belongs to; each union declares the getters all its
     * classes share.
     */
    void linkUnions() {
      for (Definition definition : definitions.values()) {
        if (!(definition instanceof UnionDef)) {
          continue;
        }
        UnionDef union = (UnionDef) definition;
        if (union.parent != null && !(definitions.get(union.parent) instanceof UnionDef)) {
          fail(union.name + " extends " + union.parent + ", which is not a union");
        }
        List<String> classes = new ArrayList<>(union.members);
        if (union.fallback != null && !classes.contains(union.fallback)) {
          classes.add(union.fallback);
        }
        for (String member : classes) {
          Definition target = definitions.get(member);
          if (!(target instanceof ClassDef)) {
            fail(union.name + ": " + member + " is not a class");
          }
          ((ClassDef) target).unions.add(union.name);
        }
        union.common = commonMembers(classes);
      }
      // A class lists only the most specific of its unions (Event, not also WebhookEvent).
      for (Definition definition : definitions.values()) {
        if (definition instanceof ClassDef) {
          ClassDef type = (ClassDef) definition;
          List<String> implied = new ArrayList<>();
          for (String union : type.unions) {
            String parent = ((UnionDef) definitions.get(union)).parent;
            if (parent != null) {
              implied.add(parent);
            }
          }
          type.unions.removeAll(implied);
        }
      }
    }

    List<MemberDef> commonMembers(List<String> classes) {
      List<MemberDef> common = new ArrayList<>();
      ClassDef first = (ClassDef) definitions.get(classes.get(0));
      for (MemberDef member : first.members) {
        boolean shared = true;
        for (String other : classes) {
          MemberDef match = null;
          for (MemberDef candidate : ((ClassDef) definitions.get(other)).members) {
            if (candidate.name.equals(member.name)) {
              match = candidate;
            }
          }
          if (match == null || !match.type.javaType.equals(member.type.javaType)) {
            shared = false;
          }
        }
        if (shared) {
          common.add(member);
        }
      }
      return common;
    }

    void defineQueries() {
      Map<String, Object> paths = asMap(document.getOrDefault("paths", Map.of()), "paths");
      for (Map.Entry<String, Object> path : paths.entrySet()) {
        for (Map.Entry<String, Object> method : asMap(path.getValue(), path.getKey()).entrySet()) {
          if (!List.of("get", "post", "put", "patch", "delete").contains(method.getKey())) {
            continue;
          }
          String label = method.getKey() + " " + path.getKey();
          Map<String, Object> operation = asMap(method.getValue(), label);
          String operationId = asString(operation.get("operationId"), label);
          String name = upperFirst(operationId) + "Params";
          ClassDef definition =
              new ClassDef(
                  name,
                  "The filters of `"
                      + operationId
                      + "` ("
                      + method.getKey().toUpperCase(Locale.ROOT)
                      + " "
                      + path.getKey()
                      + "). Every member is optional.");
          for (Object raw : asList(operation.getOrDefault("parameters", List.of()), operationId)) {
            Map<String, Object> parameter = parameter(asMap(raw, operationId), operationId);
            if (!"query".equals(parameter.get("in"))) {
              continue;
            }
            String key = asString(parameter.get("name"), operationId);
            String where = operationId + "." + key;
            if (!IDENTIFIER.matcher(key).matches()
                || JAVA_KEYWORDS.contains(key)
                || RESERVED_MEMBERS.contains(key)) {
              fail(where + ": not a valid Java method name");
            }
            Map<String, Object> schema = asMap(parameter.getOrDefault("schema", Map.of()), where);
            JType type = render(schema, name + upperFirst(key), operationId + "?" + key, where);
            String doc = joinSentences(describe(parameter), describe(schema));
            definition.members.add(new MemberDef(key, type, doc, false, false));
          }
          if (!definition.members.isEmpty() && enumNames != null) {
            define(definition);
          }
        }
      }
    }

    Map<String, Object> parameter(Map<String, Object> parameter, String where) {
      if (!parameter.containsKey("$ref")) {
        return parameter;
      }
      String target = asString(parameter.get("$ref"), where);
      String prefix = "#/components/parameters/";
      String name = target.startsWith(prefix) ? target.substring(prefix.length()) : "";
      if (!parameters.containsKey(name)) {
        fail(where + ": unknown parameter " + target);
      }
      return asMap(parameters.get(name), target);
    }

    EnumDef enumDefinition(String name, String doc, List<String> values, String place) {
      EnumDef definition = new EnumDef(name, doc);
      Set<String> constants = new LinkedHashSet<>();
      String member = place.replaceAll("^.*[.?]", "").replaceAll("[\\[\\]{}]", "");
      for (String value : values) {
        String constant = constantName(value, member, name);
        if (!constants.add(constant)) {
          fail(name + ": two values become the constant " + constant);
        }
        definition.constants.add(new String[] {constant, value});
      }
      return definition;
    }

    /** Whether a union declares the getter of a member, itself or through its parent. */
    boolean declares(String union, String member) {
      UnionDef definition = (UnionDef) definitions.get(union);
      for (MemberDef common : definition.common) {
        if (common.name.equals(member)) {
          return true;
        }
      }
      return definition.parent != null && declares(definition.parent, member);
    }

    /** Whether one of the unions a class implements declares the getter of a member. */
    boolean declaredByUnion(ClassDef type, MemberDef member) {
      for (String union : type.unions) {
        if (declares(union, member.name)) {
          return true;
        }
      }
      return false;
    }

    // Output.

    Map<String, String> files() {
      Map<String, String> files = new TreeMap<>();
      for (Definition definition : definitions.values()) {
        files.put(definition.name + ".java", definition.emit(this));
      }
      files.put("ModelRegistry.java", emitRegistry());
      return files;
    }

    String emitRegistry() {
      StringBuilder out = new StringBuilder();
      out.append(HEADER).append('\n');
      out.append("package ").append(PACKAGE).append(";\n\n");
      out.append("import java.util.HashMap;\n");
      out.append("import java.util.Map;\n");
      out.append("import java.util.function.Supplier;\n\n");
      out.append(
          "/** The value type of every generated class and union, for ModelDeserializer. */\n");
      out.append("final class ModelRegistry {\n");
      out.append(
          "  private static final Map<Class<?>, Supplier<ValueType>> TYPES = new HashMap<>();\n\n");
      for (Definition definition : definitions.values()) {
        if (definition instanceof UnionDef) {
          UnionDef union = (UnionDef) definition;
          out.append("  static final ValueType ").append(constantCase(union.name)).append(" =\n");
          out.append("      Types.union(\n");
          out.append("          ").append(union.name).append(".class,\n");
          out.append("          \"").append(union.property).append("\",\n");
          out.append("          ")
              .append(
                  union.fallback == null
                      ? "null"
                      : "Types.model(() -> " + union.fallback + ".TYPE)")
              .append(",\n");
          List<String> entries = new ArrayList<>();
          for (Map.Entry<String, String> value : union.values.entrySet()) {
            entries.add(
                "          \""
                    + value.getKey()
                    + "\", Types.model(() -> "
                    + value.getValue()
                    + ".TYPE)");
          }
          out.append(String.join(",\n", entries)).append(");\n\n");
        }
      }
      out.append("  static {\n");
      for (Definition definition : definitions.values()) {
        if (definition instanceof ClassDef) {
          out.append("    TYPES.put(")
              .append(definition.name)
              .append(".class, () -> Types.model(() -> ")
              .append(definition.name)
              .append(".TYPE));\n");
        } else if (definition instanceof UnionDef) {
          out.append("    TYPES.put(")
              .append(definition.name)
              .append(".class, () -> ")
              .append(constantCase(definition.name))
              .append(");\n");
        }
      }
      out.append("  }\n\n");
      out.append("  private ModelRegistry() {}\n\n");
      out.append("  /** The value type of a generated class or union, or null. */\n");
      out.append("  static ValueType typeOf(Class<?> type) {\n");
      out.append("    Supplier<ValueType> found = TYPES.get(type);\n");
      out.append("    return found == null ? null : found.get();\n");
      out.append("  }\n");
      out.append("}\n");
      return out.toString();
    }
  }

  // Definitions and their Java code.

  abstract static class Definition {
    final String name;
    final String doc;

    Definition(String name, String doc) {
      this.name = name;
      this.doc = doc;
    }

    abstract String emit(Generator generator);
  }

  static final class MemberDef {
    final String name;
    final JType type;
    final String doc;
    final boolean required;
    final boolean secret;

    MemberDef(String name, JType type, String doc, boolean required, boolean secret) {
      this.name = name;
      this.type = type;
      this.doc = doc;
      this.required = required;
      this.secret = secret;
    }
  }

  static final class ClassDef extends Definition {
    final List<MemberDef> members = new ArrayList<>();
    final List<String> unions = new ArrayList<>();

    ClassDef(String name, String doc) {
      super(name, doc);
    }

    @Override
    String emit(Generator generator) {
      Set<String> imports = new TreeSet<>();
      imports.add("com.fasterxml.jackson.databind.annotation.JsonDeserialize");
      imports.add("com.fasterxml.jackson.databind.annotation.JsonSerialize");
      imports.add("java.util.Map");
      for (MemberDef member : members) {
        imports.addAll(member.type.imports);
      }
      StringBuilder out = new StringBuilder();
      out.append(HEADER).append('\n');
      out.append("package ").append(PACKAGE).append(";\n\n");
      for (String type : imports) {
        out.append("import ").append(type).append(";\n");
      }
      out.append('\n');
      String summary = doc.isEmpty() ? name + "." : doc;
      out.append(javadoc(summary + " Build one with {@link #builder()}.", ""));
      out.append("@JsonSerialize(using = ModelSerializer.class)\n");
      out.append("@JsonDeserialize(using = ModelDeserializer.class)\n");
      out.append("public final class ").append(name).append(" extends FlashpiModel");
      if (!unions.isEmpty()) {
        out.append(" implements ").append(String.join(", ", unions));
      }
      out.append(" {\n");
      out.append("  private static final long serialVersionUID = 1L;\n\n");
      out.append("  static final ModelType TYPE =\n");
      out.append("      new ModelType(\n");
      out.append("          ").append(name).append(".class,\n");
      out.append("          ").append(name).append("::new");
      for (MemberDef member : members) {
        out.append(",\n          Types.member(\"")
            .append(member.name)
            .append("\", ")
            .append(member.type.typeExpression)
            .append(member.secret ? ", true" : ", false")
            .append(")");
      }
      out.append(");\n\n");
      out.append("  private ")
          .append(name)
          .append("(Map<String, Object> members, Map<String, Object> additionalProperties) {\n");
      out.append("    super(members, additionalProperties);\n");
      out.append("  }\n\n");
      out.append("  @Override\n");
      out.append("  ModelType modelType() {\n");
      out.append("    return TYPE;\n");
      out.append("  }\n\n");
      out.append("  /** A builder with no member set. */\n");
      out.append("  public static Builder builder() {\n");
      out.append("    return new Builder();\n");
      out.append("  }\n\n");
      out.append("  /** A builder with the members of this one, to change some. */\n");
      out.append("  public Builder toBuilder() {\n");
      out.append("    Builder builder = new Builder();\n");
      out.append("    builder.copy(this);\n");
      out.append("    return builder;\n");
      out.append("  }\n");
      for (MemberDef member : members) {
        out.append('\n');
        String text = member.doc.isEmpty() ? "" : member.doc + " ";
        text += member.required ? "Required. " : "";
        if (member.type.javaType.startsWith("List<") || member.type.javaType.startsWith("Map<")) {
          text += "Unmodifiable. ";
        }
        text = text.trim();
        if (member.type.kind == JType.Kind.ENUM || member.type.kind == JType.Kind.ENUM_LIST) {
          text += " A value this version of the SDK does not know reads as UNKNOWN.";
        }
        if (member.secret) {
          text += " A secret: toString() never shows it.";
        }
        if (text.isEmpty()) {
          text = "The " + member.name + ".";
        }
        out.append(
            javadoc(text.trim() + " @return the member, or null when it is null or not set", "  "));
        if (member.type.kind == JType.Kind.GENERIC) {
          out.append("  @SuppressWarnings(\"unchecked\")\n");
        }
        if (!unions.isEmpty() && generator.declaredByUnion(this, member)) {
          out.append("  @Override\n");
        }
        out.append("  public ")
            .append(member.type.javaType)
            .append(' ')
            .append(getter(member.name))
            .append("() {\n");
        out.append("    return ")
            .append(member.type.read("get(\"" + member.name + "\")"))
            .append(";\n");
        out.append("  }\n");
      }
      out.append('\n');
      out.append("  /** Builds a {@link ")
          .append(name)
          .append("}. Members left unset are not sent. */\n");
      out.append("  public static final class Builder extends FlashpiModel.Builder<Builder, ")
          .append(name)
          .append("> {\n");
      out.append("    private Builder() {\n");
      out.append("      super(TYPE);\n");
      out.append("    }\n");
      for (MemberDef member : members) {
        out.append('\n');
        String text = member.doc.isEmpty() ? "Sets " + member.name + "." : member.doc;
        out.append(
            javadoc(
                text
                    + " Null sends null. @param "
                    + member.name
                    + " the value @return this builder",
                "    "));
        out.append("    public Builder ")
            .append(member.name)
            .append('(')
            .append(member.type.javaType)
            .append(' ')
            .append(member.name)
            .append(") {\n");
        out.append("      return set(\"")
            .append(member.name)
            .append("\", ")
            .append(member.type.write(member.name))
            .append(");\n");
        out.append("    }\n");
      }
      out.append("  }\n");
      out.append("}\n");
      return out.toString();
    }
  }

  static final class EnumDef extends Definition {
    final List<String[]> constants = new ArrayList<>();

    EnumDef(String name, String doc) {
      super(name, doc);
    }

    @Override
    String emit(Generator generator) {
      StringBuilder out = new StringBuilder();
      out.append(HEADER).append('\n');
      out.append("package ").append(PACKAGE).append(";\n\n");
      out.append("import com.fasterxml.jackson.annotation.JsonCreator;\n");
      out.append("import com.fasterxml.jackson.annotation.JsonValue;\n\n");
      boolean ownUnknown = false;
      for (String[] constant : constants) {
        ownUnknown |= constant[0].equals(UNKNOWN);
      }
      String text = doc.isEmpty() ? name + "." : doc;
      text +=
          ownUnknown
              ? " A value this version of the SDK does not know also reads as UNKNOWN."
              : " A value this version of the SDK does not know reads as UNKNOWN.";
      out.append(javadoc(text, ""));
      out.append("public enum ").append(name).append(" {\n");
      List<String> lines = new ArrayList<>();
      for (String[] constant : constants) {
        lines.add(
            javadoc("{@code " + escapeJavadoc(constant[1]) + "}", "  ")
                + "  "
                + constant[0]
                + "(\""
                + constant[1]
                + "\")");
      }
      if (!ownUnknown) {
        lines.add(
            javadoc(
                    "A value this version of the SDK does not know: update the SDK to read it. It"
                        + " cannot be sent.",
                    "  ")
                + "  UNKNOWN(null)");
      }
      out.append(String.join(",\n\n", lines)).append(";\n\n");
      out.append("  private final String value;\n\n");
      out.append("  ").append(name).append("(String value) {\n");
      out.append("    this.value = value;\n");
      out.append("  }\n\n");
      out.append("  /**\n");
      out.append("   * The value on the wire.\n");
      out.append("   *\n");
      out.append(
          ownUnknown
              ? "   * @return the value\n"
              : "   * @return the value, or null for UNKNOWN\n");
      out.append("   */\n");
      out.append("  @JsonValue\n");
      out.append("  public String value() {\n");
      out.append("    return value;\n");
      out.append("  }\n\n");
      out.append("  /**\n");
      out.append("   * The constant of a value on the wire.\n");
      out.append("   *\n");
      out.append("   * @param value the value\n");
      out.append(
          "   * @return its constant, UNKNOWN for a value this version does not know, or null for null\n");
      out.append("   */\n");
      out.append("  @JsonCreator\n");
      out.append("  public static ").append(name).append(" fromValue(String value) {\n");
      out.append("    if (value == null) {\n");
      out.append("      return null;\n");
      out.append("    }\n");
      out.append("    for (").append(name).append(" constant : values()) {\n");
      out.append("      if (value.equals(constant.value)) {\n");
      out.append("        return constant;\n");
      out.append("      }\n");
      out.append("    }\n");
      out.append("    return UNKNOWN;\n");
      out.append("  }\n");
      out.append("}\n");
      return out.toString();
    }
  }

  static final class UnionDef extends Definition {
    final String property;
    final List<String> members;
    final Map<String, String> values;
    String fallback;
    String parent;
    List<MemberDef> common = new ArrayList<>();

    UnionDef(
        String name,
        String doc,
        String property,
        List<String> members,
        Map<String, String> values) {
      super(name, doc);
      this.property = property;
      this.members = members;
      this.values = values;
    }

    @Override
    String emit(Generator generator) {
      Set<String> imports = new TreeSet<>();
      imports.add("com.fasterxml.jackson.databind.annotation.JsonDeserialize");
      List<MemberDef> declared = new ArrayList<>();
      for (MemberDef member : common) {
        if (parent == null || !generator.declares(parent, member.name)) {
          declared.add(member);
          imports.addAll(member.type.imports);
        }
      }
      StringBuilder out = new StringBuilder();
      out.append(HEADER).append('\n');
      out.append("package ").append(PACKAGE).append(";\n\n");
      for (String type : imports) {
        out.append("import ").append(type).append(";\n");
      }
      out.append('\n');
      String classes = String.join(", ", members);
      String text =
          (doc.isEmpty() ? name + "." : doc)
              + " One of "
              + classes
              + ", by its {@code "
              + property
              + "}"
              + (fallback == null ? "" : "; " + fallback + " for a type this version does not know")
              + ": check it with instanceof.";
      out.append(javadoc(text, ""));
      out.append("@JsonDeserialize(using = ModelDeserializer.class)\n");
      out.append("public interface ").append(name);
      if (parent != null) {
        out.append(" extends ").append(parent);
      }
      if (declared.isEmpty()) {
        out.append(" {}\n");
        return out.toString();
      }
      out.append(" {");
      for (MemberDef member : declared) {
        out.append("\n");
        out.append(
            javadoc(
                (member.doc.isEmpty() ? "The " + member.name + "." : member.doc)
                    + " @return the member",
                "  "));
        out.append("  ")
            .append(member.type.javaType)
            .append(' ')
            .append(getter(member.name))
            .append("();\n");
      }
      out.append("}\n");
      return out.toString();
    }
  }

  // Java types.

  static final class JType {
    enum Kind {
      SIMPLE,
      ENUM,
      ENUM_LIST,
      GENERIC
    }

    final String javaType;
    final String typeExpression;
    final Kind kind;
    final String enumName;
    final Set<String> imports = new TreeSet<>();

    JType(String javaType, String typeExpression, Kind kind, String enumName) {
      this.javaType = javaType;
      this.typeExpression = typeExpression;
      this.kind = kind;
      this.enumName = enumName;
    }

    static JType simple(String javaType, String typeExpression) {
      return new JType(javaType, typeExpression, Kind.SIMPLE, null);
    }

    static JType model(String name) {
      return new JType(name, "Types.model(() -> " + name + ".TYPE)", Kind.SIMPLE, null);
    }

    static JType union(String name) {
      return new JType(
          name, "Types.lazy(() -> ModelRegistry." + constantCase(name) + ")", Kind.SIMPLE, null);
    }

    static JType enumeration(String name) {
      return new JType(name, "Types.STRING", Kind.ENUM, name);
    }

    static JType list(JType item) {
      if (item.kind == Kind.ENUM) {
        JType type =
            new JType(
                "List<" + item.javaType + ">",
                "Types.list(Types.STRING)",
                Kind.ENUM_LIST,
                item.enumName);
        type.imports.add("java.util.List");
        return type;
      }
      if (item.kind == Kind.ENUM_LIST) {
        fail("Lists of lists of enums are not supported");
      }
      JType type =
          new JType(
              "List<" + item.javaType + ">",
              "Types.list(" + item.typeExpression + ")",
              Kind.GENERIC,
              null);
      type.imports.addAll(item.imports);
      type.imports.add("java.util.List");
      return type;
    }

    static JType map(JType value) {
      if (value.kind == Kind.ENUM || value.kind == Kind.ENUM_LIST) {
        fail("Maps of enums are not supported");
      }
      JType type =
          new JType(
              "Map<String, " + value.javaType + ">",
              "Types.map(" + value.typeExpression + ")",
              Kind.GENERIC,
              null);
      type.imports.addAll(value.imports);
      type.imports.add("java.util.Map");
      return type;
    }

    JType importing(String type) {
      imports.add(type);
      return this;
    }

    /** The expression a getter returns, from the stored value `stored`. */
    String read(String stored) {
      switch (kind) {
        case ENUM:
          return enumName + ".fromValue((String) " + stored + ")";
        case ENUM_LIST:
          return "Types.enumList(" + stored + ", " + enumName + "::fromValue)";
        default:
          return "(" + javaType + ") " + stored;
      }
    }

    /** The expression a builder stores, from the argument `argument`. */
    String write(String argument) {
      switch (kind) {
        case ENUM:
          return "Types.wireValue("
              + argument
              + " == null ? null : "
              + argument
              + ".value(), "
              + argument
              + ")";
        case ENUM_LIST:
          return "Types.wireValues(" + argument + ", " + enumName + "::value)";
        case GENERIC:
          return javaType.startsWith("List<")
              ? "Types.copyList(" + argument + ")"
              : "Types.copyMap(" + argument + ")";
        default:
          return argument;
      }
    }
  }

  // Helpers of the generator.

  static String getter(String member) {
    return "get" + upperFirst(member);
  }

  static String upperFirst(String value) {
    return value.isEmpty() ? value : Character.toUpperCase(value.charAt(0)) + value.substring(1);
  }

  /** UPPER_SNAKE_CASE of a camelCase name: WebhookEvent to WEBHOOK_EVENT. */
  static String constantCase(String name) {
    return name.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toUpperCase(Locale.ROOT);
  }

  /**
   * The constant of an enum value: authorized to AUTHORIZED, invoice.authorized to
   * INVOICE_AUTHORIZED.
   */
  static String constantName(String value, String member, String enumName) {
    if (SYMBOL_CONSTANTS.containsKey(value)) {
      return SYMBOL_CONSTANTS.get(value);
    }
    String constant =
        value
            .replaceAll("([a-z0-9])([A-Z])", "$1_$2")
            .replaceAll("[^A-Za-z0-9]+", "_")
            .replaceAll("^_+|_+$", "")
            .toUpperCase(Locale.ROOT);
    if (constant.isEmpty()) {
      fail(enumName + ": the value \"" + value + "\" needs an entry in SYMBOL_CONSTANTS");
    }
    if (Character.isDigit(constant.charAt(0))) {
      // Numbers such as tax rates: RATE_15.
      constant = constantCase(member) + "_" + constant;
    }
    return constant;
  }

  static String describe(Map<String, Object> schema) {
    List<String> parts = new ArrayList<>();
    Object description = schema.get("description");
    if (description instanceof String && !((String) description).isBlank()) {
      parts.add(String.join(" ", ((String) description).trim().split("\\s+")));
    }
    Object format = schema.get("format");
    if (format instanceof String
        && !List.of("binary", "password", "date", "date-time").contains(format)) {
      parts.add("Format: " + format + ".");
    }
    if (schema.containsKey("default")) {
      parts.add("Default: `" + Json.write(schema.get("default")) + "`.");
    }
    return String.join(" ", parts);
  }

  static String joinSentences(String first, String second) {
    return Stream.of(first, second)
        .filter(part -> !part.isEmpty())
        .collect(Collectors.joining(" "));
  }

  /** Markdown-ish text as Javadoc: `code` spans, escaped HTML, wrapped at 100 columns. */
  static String javadoc(String text, String indent) {
    String body = text;
    String tags = "";
    int tag = indexOfTag(body);
    if (tag >= 0) {
      tags = body.substring(tag).trim();
      body = body.substring(0, tag).trim();
    }
    StringBuilder escaped = new StringBuilder();
    String[] spans = body.split("`", -1);
    for (int index = 0; index < spans.length; index++) {
      String span = spans[index];
      boolean code = index % 2 == 1 && index < spans.length - 1;
      if (code) {
        escaped.append("{@code ").append(escapeCode(span)).append('}');
      } else if (span.contains("{@code ")) {
        escaped.append(span);
      } else {
        escaped.append(escapeJavadoc(span));
      }
    }
    List<String> lines = new ArrayList<>(wrap(escaped.toString(), 100 - indent.length() - 3));
    if (!tags.isEmpty()) {
      lines.add("");
      for (String part : tags.split("(?= @(?:param|return) )")) {
        lines.addAll(wrap(part.trim(), 100 - indent.length() - 3));
      }
    }
    if (lines.size() == 1 && indent.length() + lines.get(0).length() + 7 <= 100) {
      return indent + "/** " + lines.get(0) + " */\n";
    }
    StringBuilder out = new StringBuilder(indent).append("/**\n");
    for (String line : lines) {
      out.append(indent).append(line.isEmpty() ? " *" : " * " + line).append('\n');
    }
    return out.append(indent).append(" */\n").toString();
  }

  static int indexOfTag(String text) {
    int param = text.indexOf(" @param ");
    int result = text.indexOf(" @return ");
    if (param < 0) {
      return result;
    }
    return result < 0 ? param : Math.min(param, result);
  }

  static String escapeJavadoc(String text) {
    return text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("*/", "*&#47;")
        .replaceAll("(?<!\\{)@", "&#64;")
        .replace("\\u", "\\\\u");
  }

  static String escapeCode(String text) {
    // Inside {@code}, braces must balance and */ must not appear.
    String escaped = text.replace("*/", "*&#47;").replace("\\u", "\\\\u").replace("@", "&#64;");
    long open = escaped.chars().filter(c -> c == '{').count();
    long close = escaped.chars().filter(c -> c == '}').count();
    return open == close ? escaped : escaped.replace("{", "&#123;").replace("}", "&#125;");
  }

  static List<String> wrap(String text, int width) {
    List<String> lines = new ArrayList<>();
    StringBuilder line = new StringBuilder();
    for (String word : text.split(" ")) {
      if (word.isEmpty()) {
        continue;
      }
      if (line.length() > 0 && line.length() + 1 + word.length() > width) {
        lines.add(line.toString());
        line.setLength(0);
      }
      if (line.length() > 0) {
        line.append(' ');
      }
      line.append(word);
    }
    if (line.length() > 0 || lines.isEmpty()) {
      lines.add(line.toString());
    }
    return lines;
  }

  @SuppressWarnings("unchecked")
  static Map<String, Object> asMap(Object value, String where) {
    if (!(value instanceof Map)) {
      fail(where + ": expected an object");
    }
    return (Map<String, Object>) value;
  }

  @SuppressWarnings("unchecked")
  static List<Object> asList(Object value, String where) {
    if (!(value instanceof List)) {
      fail(where + ": expected a list");
    }
    return (List<Object>) value;
  }

  static String asString(Object value, String where) {
    if (!(value instanceof String)) {
      fail(where + ": expected a string");
    }
    return (String) value;
  }

  static Map<String, String> orderedMap(String... pairs) {
    Map<String, String> map = new LinkedHashMap<>();
    for (int index = 0; index < pairs.length; index += 2) {
      map.put(pairs[index], pairs[index + 1]);
    }
    return Collections.unmodifiableMap(map);
  }

