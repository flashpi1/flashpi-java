  // Downloading the contract.

  /** Where the contract came from, and its text. */
  static String[] download() throws IOException, InterruptedException {
    String file = System.getenv("FLASHPI_OPENAPI_FILE");
    if (file != null && !file.isEmpty()) {
      return new String[] {file, Files.readString(Paths.get(file), StandardCharsets.UTF_8)};
    }
    String url = System.getenv().getOrDefault("FLASHPI_OPENAPI_URL", DEFAULT_URL);
    HttpClient client =
        HttpClient.newBuilder()
            .followRedirects(HttpClient.Redirect.NEVER)
            .connectTimeout(Duration.ofSeconds(30))
            .build();
    URI uri = URI.create(url);
    // Redirects are followed by hand, to HTTPS URLs only (the JDK would follow none here).
    for (int hop = 0; hop < 5; hop++) {
      if (!"https".equals(uri.getScheme())) {
        throw new IOException("Refusing a contract from a non-HTTPS URL: " + uri);
      }
      HttpRequest request =
          HttpRequest.newBuilder(uri)
              .header("accept", "application/json")
              .timeout(Duration.ofSeconds(60))
              .GET()
              .build();
      HttpResponse<byte[]> response = client.send(request, HttpResponse.BodyHandlers.ofByteArray());
      int status = response.statusCode();
      if (status >= 300 && status < 400) {
        String location =
            response
                .headers()
                .firstValue("location")
                .orElseThrow(() -> new IOException("A redirect without Location"));
        uri = uri.resolve(location);
        continue;
      }
      if (status != 200) {
        throw new IOException("Downloading " + uri + " answered " + status);
      }
      return new String[] {url, new String(response.body(), StandardCharsets.UTF_8)};
    }
    throw new IOException("Too many redirects from " + url);
  }

  // A small JSON reader and writer: objects are LinkedHashMaps (members in document order),
  // numbers BigDecimals.

  static final class Json {
    private final String text;
    private int at;

    private Json(String text) {
      this.text = text;
    }

    static Object parse(String text) {
      Json json = new Json(text);
      json.space();
      Object value = json.value();
      json.space();
      if (json.at != text.length()) {
        json.error("unexpected text after the document");
      }
      return value;
    }

    static String write(Object value) {
      if (value == null) {
        return "null";
      }
      if (value instanceof String) {
        StringBuilder out = new StringBuilder("\"");
        for (char c : ((String) value).toCharArray()) {
          if (c == '"' || c == '\\') {
            out.append('\\').append(c);
          } else if (c < 0x20) {
            out.append(String.format("\\u%04x", (int) c));
          } else {
            out.append(c);
          }
        }
        return out.append('"').toString();
      }
      if (value instanceof BigDecimal) {
        return ((BigDecimal) value).toPlainString();
      }
      if (value instanceof Boolean) {
        return value.toString();
      }
      if (value instanceof List) {
        return ((List<?>) value)
            .stream().map(Json::write).collect(Collectors.joining(",", "[", "]"));
      }
      return ((Map<?, ?>) value)
          .entrySet().stream()
              .map(entry -> write(entry.getKey()) + ":" + write(entry.getValue()))
              .collect(Collectors.joining(",", "{", "}"));
    }

    private Object value() {
      if (at >= text.length()) {
        error("unexpected end");
      }
      char c = text.charAt(at);
      switch (c) {
        case '{':
          return object();
        case '[':
          return array();
        case '"':
          return string();
        case 't':
          return literal("true", Boolean.TRUE);
        case 'f':
          return literal("false", Boolean.FALSE);
        case 'n':
          return literal("null", null);
        default:
          return number();
      }
    }

    private Map<String, Object> object() {
      Map<String, Object> members = new LinkedHashMap<>();
      at++;
      space();
      if (peek('}')) {
        at++;
        return members;
      }
      while (true) {
        space();
        if (!peek('"')) {
          error("expected a member name");
        }
        String name = string();
        space();
        expect(':');
        space();
        if (members.containsKey(name)) {
          error("the member " + name + " appears twice");
        }
        members.put(name, value());
        space();
        if (peek(',')) {
          at++;
          continue;
        }
        expect('}');
        return members;
      }
    }

    private List<Object> array() {
      List<Object> items = new ArrayList<>();
      at++;
      space();
      if (peek(']')) {
        at++;
        return items;
      }
      while (true) {
        space();
        items.add(value());
        space();
        if (peek(',')) {
          at++;
          continue;
        }
        expect(']');
        return items;
      }
    }

    private String string() {
      StringBuilder out = new StringBuilder();
      at++;
      while (true) {
        if (at >= text.length()) {
          error("unterminated string");
        }
        char c = text.charAt(at++);
        if (c == '"') {
          return out.toString();
        }
        if (c == '\\') {
          char escape = text.charAt(at++);
          switch (escape) {
            case '"':
            case '\\':
            case '/':
              out.append(escape);
              break;
            case 'b':
              out.append('\b');
              break;
            case 'f':
              out.append('\f');
              break;
            case 'n':
              out.append('\n');
              break;
            case 'r':
              out.append('\r');
              break;
            case 't':
              out.append('\t');
              break;
            case 'u':
              out.append((char) Integer.parseInt(text.substring(at, at + 4), 16));
              at += 4;
              break;
            default:
              error("bad escape");
          }
        } else if (c < 0x20) {
          error("a control character in a string");
        } else {
          out.append(c);
        }
      }
    }

    private Object literal(String word, Object value) {
      if (!text.startsWith(word, at)) {
        error("unexpected token");
      }
      at += word.length();
      return value;
    }

    private BigDecimal number() {
      int start = at;
      while (at < text.length() && "+-0123456789.eE".indexOf(text.charAt(at)) >= 0) {
        at++;
      }
      try {
        return new BigDecimal(text.substring(start, at));
      } catch (NumberFormatException error) {
        error("bad number");
        return null;
      }
    }

    private boolean peek(char c) {
      return at < text.length() && text.charAt(at) == c;
    }

    private void expect(char c) {
      if (!peek(c)) {
        error("expected " + c);
      }
      at++;
    }

    private void space() {
      while (at < text.length() && " \t\r\n".indexOf(text.charAt(at)) >= 0) {
        at++;
      }
    }

    private void error(String message) {
      throw new GenerationError("openapi.json, offset " + at + ": " + message);
    }
  }
